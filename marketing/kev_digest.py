"""Weekly CISA KEV digest: one page per ISO week at /kev/<yyyy>-w<ww>/.

For every CVE CISA added to the Known Exploited Vulnerabilities catalog in
the week, the page lists FIRST.org EPSS, public-exploit availability
(Exploit-DB / Metasploit), ransomware use, the CISA due date and whether
ShadowSecurityScanner ships an active check for it. Facts only, all from
public feeds — nothing is generated by a language model.

    python kev_digest.py            # the previous ISO week (scheduled run)
    python kev_digest.py 2026-W41   # a specific week (backfill)
"""
from __future__ import annotations

import datetime as dt
import gzip
import json
import re
import sys

from lib import (DATA, ROOT, SITE, cta, enqueue_post, esc, get_json, http, load_json, load_state,
                 log, page, save_json, save_state, sitemap_upsert, today, warn, write_if_changed)

KEV_URL = "https://raw.githubusercontent.com/cisagov/kev-data/develop/known_exploited_vulnerabilities.json"
EPSS_URL = "https://api.first.org/data/v1/epss?cve="
FEED = "https://safetylab.github.io/ShadowSecurityScanner/"
WEEKS_PATH = DATA / "kev-weeks.json"


def week_bounds(spec: str | None) -> tuple:
    if spec:
        m = re.match(r"^(\d{4})-?W(\d{1,2})$", spec, re.I)
        if not m:
            sys.exit(f"bad week {spec!r}, expected YYYY-Www")
        start = dt.date.fromisocalendar(int(m.group(1)), int(m.group(2)), 1)
    else:
        start = today() - dt.timedelta(days=today().weekday() + 7)
    year, week, _ = start.isocalendar()
    return start, start + dt.timedelta(days=6), f"{year}-w{week:02d}"


def pack_cves(name: str) -> set:
    """CVE ids referenced by one pack of the scanner's public audit feed."""
    try:
        raw = http("GET", FEED + name, timeout=120)[1]
    except Exception as e:  # coverage is a nice-to-have; never block the digest
        warn(f"feed pack {name} unavailable: {e}")
        return set()
    entries = json.loads(gzip.decompress(raw))["entries"]
    return {c.upper() for e in entries for c in (e.get("cves") or []) if c.upper().startswith("CVE-")}


def epss_scores(cves: list) -> dict:
    scores = {}
    for i in range(0, len(cves), 50):
        try:
            data = get_json(EPSS_URL + ",".join(cves[i:i + 50]))["data"]
        except Exception as e:
            warn(f"EPSS lookup failed: {e}")
            continue
        for d in data:
            scores[d["cve"]] = (float(d["epss"]), float(d["percentile"]))
    return scores


def fmt_range(a: dt.date, b: dt.date) -> str:
    if a.month == b.month:
        return f"{a:%b} {a.day}–{b.day}, {b.year}"
    return f"{a:%b} {a.day} – {b:%b} {b.day}, {b.year}"


def product(v: dict) -> str:
    """"ProFTPD ProFTPD" → "ProFTPD"; "Apache Struts" stays as is."""
    vendor, prod = v["vendorProject"].strip(), v["product"].strip()
    return prod if prod.lower().startswith(vendor.lower()) else f"{vendor} {prod}"


def links(notes: str) -> list:
    return [u.rstrip(".;,") for u in re.findall(r"https?://\S+", notes or "")]


def render(slug: str, start: dt.date, end: dt.date, rows: list, catalog_total: int) -> tuple:
    up = "../../"
    week_no = int(slug.split("-w")[1])
    span = fmt_range(start, end)
    n = len(rows)
    ransom = sum(r["ransomware"] for r in rows)
    exploit = sum(bool(r["exploit"]) for r in rows)
    covered = sum(r["covered"] for r in rows)
    high = [r for r in rows if r["epss"] is not None and r["epss"] >= 0.1]

    def epss_cell(r):
        if r["epss"] is None:
            return "—"
        return f'{r["epss"] * 100:.1f}% <span class="meta">(p{r["pct"] * 100:.0f})</span>'

    table = "\n".join(f"""          <tr>
            <th scope="row" style="white-space:nowrap"><a href="#{r['cve'].lower()}">{r['cve']}</a></th>
            <td>{esc(r['product'])}</td>
            <td>{epss_cell(r)}</td>
            <td>{esc(r['exploit']) or '—'}</td>
            <td>{'<span class="badge-kev">yes</span>' if r['ransomware'] else '—'}</td>
            <td style="white-space:nowrap">{r['due']}</td>
            <td{' class="yes"' if r['covered'] else ''}>{'Active check' if r['covered'] else 'Catalog'}</td>
          </tr>""" for r in rows)

    details = "\n".join(f"""    <h2 id="{r['cve'].lower()}">{r['cve']} — {esc(r['name'])}</h2>
    <p>{esc(r['desc'])}</p>
    <ul>
      <li><strong>Added to KEV:</strong> {r['added']} · <strong>CISA due date:</strong> {r['due']}</li>
      <li><strong>EPSS:</strong> {epss_cell(r)} · <strong>Public exploit:</strong> {esc(r['exploit']) or 'none known'} · <strong>Ransomware use:</strong> {'known' if r['ransomware'] else 'not known'}</li>
      {f"<li><strong>Weakness:</strong> {esc(', '.join(r['cwes']))}</li>" if r['cwes'] else ''}
      <li><strong>Required action:</strong> {esc(r['action'])}</li>
      <li><strong>References:</strong> {' · '.join(f'<a href="{esc(u)}" rel="noreferrer nofollow">{esc(re.sub(r"^https?://(www[.])?", "", u).split("/")[0])}</a>' for u in r['links'][:6])}</li>
    </ul>""" for r in rows)

    summary = (f"CISA added <strong>{n}</strong> vulnerabilit{'y' if n == 1 else 'ies'} to the Known "
               f"Exploited Vulnerabilities catalog between {span}: each one is confirmed to be "
               f"exploited in the wild. {ransom} {'is' if ransom == 1 else 'are'} linked to ransomware "
               f"campaigns, {exploit} {'has' if exploit == 1 else 'have'} a public exploit, and "
               f"{len(high)} {'has' if len(high) == 1 else 'have'} an EPSS score of 10% or more. "
               f"The catalog now holds {catalog_total} entries.")
    body = f"""  <article class="article">
    <div class="article-head">
      <span class="eyebrow">KEV weekly digest · week {week_no}</span>
      <h1>Known exploited vulnerabilities: {span}</h1>
      <p class="meta">{n} new CISA KEV entries · EPSS as of {today().isoformat()}</p>
    </div>
    <p>{summary}</p>
    <h2>Fix-first order</h2>
    <p>Sorted the way <a href="{up}guides/what-is-epss-and-kev/">exploit-aware triage</a> works:
    ransomware-linked first, then by EPSS exploit probability.</p>
    <div class="table-wrap" style="margin:0 0 20px">
      <table class="cmp">
        <thead>
          <tr><th scope="col">CVE</th><th scope="col">Product</th><th scope="col">EPSS</th><th scope="col">Public exploit</th><th scope="col">Ransomware</th><th scope="col">CISA due</th><th scope="col">Scanner</th></tr>
        </thead>
        <tbody>
{table}
        </tbody>
      </table>
    </div>
    <p class="meta"><strong>Scanner</strong>: “Active check” means ShadowSecurityScanner ships a
    network or web probe for this CVE; “Catalog” means it is tracked in the KEV-synced audit catalog
    and flagged when version fingerprinting matches.{f" {covered} of {n} have an active check." if covered else ""}</p>
{details}
    <h2>How to find these on your network</h2>
    <p>Every KEV entry is flagged automatically in ShadowSecurityScanner: findings are sorted KEV →
    EPSS → severity, and a daily catalog update pulls new KEV entries without a reinstall. See
    <a href="{up}guides/how-to-run-a-network-vulnerability-scan/">how to run a network vulnerability scan</a>.</p>
{cta(up, "Scan for known-exploited vulnerabilities", "Free and open-source, with CISA KEV and EPSS built in.")}
    <p class="meta">Sources: <a href="https://www.cisa.gov/known-exploited-vulnerabilities-catalog" rel="noreferrer">CISA KEV</a>,
    <a href="https://www.first.org/epss/" rel="noreferrer">FIRST.org EPSS</a>, Exploit-DB, Metasploit. ·
    <a href="../">All weekly digests</a></p>
  </article>"""
    title = f"CISA KEV weekly digest: {span} ({n} new exploited CVEs)"
    desc = (f"{n} vulnerabilities CISA added to KEV in week {week_no} of {start.isocalendar()[0]}, "
            f"with EPSS scores, public exploits, ransomware use and due dates.")
    html_ = page(
        path=f"kev/{slug}/", title=title, description=desc, body=body,
        breadcrumbs=[("KEV digest", "kev/"), (f"Week {week_no}", f"kev/{slug}/")],
        header_link=("KEV digest", "kev/"),
        jsonld=[{
            "@type": "TechArticle", "headline": title[:110], "description": desc,
            "datePublished": (end + dt.timedelta(days=1)).isoformat(),
            "author": {"@type": "Person", "name": "AndriiGordiienko"},
            "image": f"{SITE}/assets/og-image.png",
            "mainEntityOfPage": f"{SITE}/kev/{slug}/",
            "about": [{"@type": "Thing", "name": r["cve"]} for r in rows],
        }])
    return html_, title, desc


def render_index(weeks: dict) -> str:
    up = "../"
    cards = "\n".join(f"""      <a class="card" href="{slug}/">
        <div class="card-ic">🔥</div>
        <h3>{esc(w['span'])}</h3>
        <p>{w['count']} new KEV entries{f" · top EPSS: {esc(w['top'])}" if w.get('top') else ''}</p>
      </a>""" for slug, w in sorted(weeks.items(), reverse=True))
    body = f"""  <section class="section">
    <div class="section-head">
      <span class="eyebrow">KEV digest</span>
      <h1>CISA KEV weekly digest</h1>
      <p>Every week: the vulnerabilities CISA confirmed as exploited in the wild, ranked by EPSS
      exploit probability, with public exploits, ransomware use and patch deadlines.</p>
    </div>
    <div class="guide-cards">
{cards}
    </div>
  </section>
  <article class="article" style="padding-top:0">
{cta(up, "Find KEV vulnerabilities on your network", "ShadowSecurityScanner flags every KEV entry and sorts by EPSS.")}
  </article>"""
    return page(path="kev/", title="CISA KEV weekly digest — exploited vulnerabilities by week",
                description="Weekly digest of CVEs added to the CISA Known Exploited Vulnerabilities "
                            "catalog, with EPSS scores, public exploits and due dates.",
                body=body, breadcrumbs=[("KEV digest", "kev/")], og_type="website",
                header_link=("Guides", "guides/"),
                jsonld=[{"@type": "CollectionPage", "name": "CISA KEV weekly digest",
                         "url": f"{SITE}/kev/"}])


def main(spec: str | None = None) -> bool:
    start, end, slug = week_bounds(spec)
    kev = get_json(KEV_URL)
    vulns = [v for v in kev["vulnerabilities"]
             if start.isoformat() <= v["dateAdded"] <= end.isoformat()]
    weeks = load_json(WEEKS_PATH, {})
    if not vulns:
        log(f"KEV {slug}: no additions — nothing to publish")
        return False

    cves = sorted({v["cveID"] for v in vulns})
    scores = epss_scores(cves)
    active = pack_cves("nuclei.json.gz") | pack_cves("sss_chk.json.gz")
    edb, msf = pack_cves("exploitdb.json.gz"), pack_cves("metasploit.json.gz")

    rows = []
    for v in vulns:
        cve = v["cveID"]
        epss, pct = scores.get(cve, (None, None))
        rows.append({
            "cve": cve, "vendor": v["vendorProject"], "product": product(v),
            "name": v["vulnerabilityName"], "desc": v["shortDescription"],
            "added": v["dateAdded"], "due": v["dueDate"], "action": v["requiredAction"],
            "ransomware": v.get("knownRansomwareCampaignUse") == "Known",
            "cwes": v.get("cwes") or [], "links": links(v.get("notes", "")),
            "epss": epss, "pct": pct, "covered": cve in active,
            "exploit": " + ".join(n for n, s in (("Metasploit", msf), ("Exploit-DB", edb)) if cve in s),
        })
    rows.sort(key=lambda r: (not r["ransomware"], -(r["epss"] or 0), r["cve"]))

    html_, title, desc = render(slug, start, end, rows, kev["count"])
    changed = write_if_changed(ROOT / "kev" / slug / "index.html", html_)
    top = rows[0]
    weeks[slug] = {"span": fmt_range(start, end), "count": len(rows),
                   "top": f"{top['cve']} ({top['product']})"}
    save_json(WEEKS_PATH, weeks)
    changed |= write_if_changed(ROOT / "kev" / "index.html", render_index(weeks))
    if changed:
        published = (end + dt.timedelta(days=1)).isoformat()
        sitemap_upsert([(f"kev/{slug}/", published, "monthly", "0.6"),
                        ("kev/", published, "weekly", "0.7")])

    # Announce only the regular weekly run, not backfills of old weeks.
    if spec is None:
        state = load_state()
        if slug not in state.setdefault("kev_announced", []):
            picks = ", ".join(f"{r['cve']} ({r['vendor']})" for r in rows[:2])
            short = (f"CISA added {len(rows)} exploited vulns to KEV last week ({fmt_range(start, end)}). "
                     f"Top risk: {picks}. EPSS, exploits and deadlines:")
            if len(short) > 230:
                short = (f"CISA added {len(rows)} exploited vulns to KEV last week. "
                         f"Top risk: {rows[0]['cve']}. EPSS, exploits and deadlines:")
            lines = "\n".join(
                f"• {r['cve']} — {r['product']}"
                + (f", EPSS {r['epss'] * 100:.0f}%" if r["epss"] is not None else "")
                + (", ransomware" if r["ransomware"] else "") for r in rows[:5])
            long = (f"CISA KEV weekly digest, {fmt_range(start, end)}: {len(rows)} newly confirmed "
                    f"exploited vulnerabilities.\n\nFix first:\n{lines}"
                    + (f"\n…and {len(rows) - 5} more." if len(rows) > 5 else "")
                    + "\n\nFull table with EPSS, public exploits, ransomware use and CISA due dates:")
            enqueue_post(f"kev-{slug}", url=f"{SITE}/kev/{slug}/", title=title, description=desc,
                         short=short, long=long,
                         tags=["CISA", "KEV", "infosec", "vulnerabilitymanagement"])
            state["kev_announced"] = (state["kev_announced"] + [slug])[-30:]
            save_state(state)
    log(f"KEV {slug}: {len(rows)} entries, page changed: {changed}")
    return changed


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else None)
